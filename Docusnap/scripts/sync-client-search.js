#!/usr/bin/env node
'use strict';
/**
 * scripts/sync-client-search.js — DRIFT GUARD #1 (generator half) for the shared search UI
 * (client search parity, 2026-09-13; Oracle C4 + S1 conditions).
 *
 * The search screen has ONE canonical source, src/windows/shared/search-ui/. The detached client is a
 * SEPARATE electron-builder app whose navGuard hard-restricts file:// loads to client/renderer/ and whose
 * asar packs only client/**, so it cannot load a file under src/ at runtime. It therefore ships GENERATED
 * COPIES under client/renderer/shared/ — produced by this script, COMMITTED (so a fresh clone + `electron .`
 * works and electron-builder packs them with zero config), and regenerated by the client's `prestart` /
 * `predist` hooks. scripts/test_client_search_sync.js (in `npm run test:pins`) fails whenever a committed
 * copy is stale, so a core search edit cannot ship without its client twin.
 *
 * MIRROR SETS (each: source → destination, mirror semantics — files removed at the source are removed from
 * the copy):
 *   search-ui  src/windows/shared/search-ui/*.js|css (never the pins) → client/renderer/shared/search-ui/  (+ banner)
 *   theme      src/windows/shared/theme.css                           → client/renderer/shared/theme.css   (+ banner)
 *              (the pop-out loads the REAL theme — the client's hand-copied token sheet lacked the tokens the
 *              search CSS needs: --sans/--accent-bg/--accent-border/--err-bg/--warn-bg/--ok-bg/--doc-bg)
 *   fonts      src/windows/shared/fonts/*.woff2                       → client/renderer/shared/fonts/       (binary, verbatim)
 *   patterns   src/windows/shared/patterns/*.svg                      → client/renderer/shared/patterns/    (verbatim)
 * Text copies get a one-line GENERATED banner (the checker hashes the copy minus that line); line endings are
 * copied as-is (the checker normalises CRLF, so core.autocrlf cannot flip it red); binaries hash raw bytes.
 *
 *   node scripts/sync-client-search.js          # regenerate every copy
 *   node scripts/sync-client-search.js --check  # exit 1 if any copy is stale (no writes)
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SHARED = path.join(ROOT, 'src', 'windows', 'shared');
const CLIENT_SHARED = path.join(ROOT, 'client', 'renderer', 'shared');
const SRC = path.join(SHARED, 'search-ui');
const DST = path.join(CLIENT_SHARED, 'search-ui');
const BANNER_LINE = '// GENERATED by scripts/sync-client-search.js from src/windows/shared/search-ui — EDIT THE SOURCE, never this copy.';
const CSS_BANNER_LINE = '/* GENERATED by scripts/sync-client-search.js from src/windows/shared/search-ui — EDIT THE SOURCE, never this copy. */';
const THEME_BANNER_LINE = '/* GENERATED by scripts/sync-client-search.js from src/windows/shared/theme.css — EDIT THE SOURCE, never this copy. */';

const SETS = [
  { name: 'search-ui', src: SRC, dst: DST, match: (f) => /\.(js|css)$/.test(f) && !/^test_/.test(f), banner: (f) => (f.endsWith('.css') ? CSS_BANNER_LINE : BANNER_LINE), binary: false },
  { name: 'theme',     src: SHARED, dst: CLIENT_SHARED, match: (f) => f === 'theme.css', banner: () => THEME_BANNER_LINE, binary: false },
  { name: 'fonts',     src: path.join(SHARED, 'fonts'), dst: path.join(CLIENT_SHARED, 'fonts'), match: (f) => /\.woff2$/.test(f), banner: null, binary: true },
  { name: 'patterns',  src: path.join(SHARED, 'patterns'), dst: path.join(CLIENT_SHARED, 'patterns'), match: (f) => /\.svg$/.test(f), banner: null, binary: false },
];

function listSrc(set) { return fs.existsSync(set.src) ? fs.readdirSync(set.src).filter(f => fs.statSync(path.join(set.src, f)).isFile() && set.match(f)).sort() : []; }
// Files that ship to the client from the search-ui set (kept for the pin's API).
function sourceFiles() { return listSrc(SETS[0]); }
function bannerFor(f) { return f.endsWith('.css') ? CSS_BANNER_LINE : BANNER_LINE; }

// The generated content for one source file: banner (text sets) + the source verbatim.
function generatedFor(set, f) {
  const p = path.join(set.src, f);
  if (set.binary) return fs.readFileSync(p);
  const src = fs.readFileSync(p, 'utf8');
  if (!set.banner) return src;
  const nl = src.includes('\r\n') ? '\r\n' : '\n';
  return set.banner(f) + nl + src;
}
function generated(f) { return generatedFor(SETS[0], f); }

const norm = (s) => String(s).replace(/\r\n/g, '\n');
const sha = (s) => crypto.createHash('sha256').update(Buffer.isBuffer(s) ? s : norm(s)).digest('hex');
const shaFile = (set, p) => (set.binary ? sha(fs.readFileSync(p)) : sha(fs.readFileSync(p, 'utf8')));

/** Compare copies vs sources for one set. */
function diffSet(set) {
  const files = listSrc(set);
  const stale = [], missing = [], extra = [];
  for (const f of files) {
    const dst = path.join(set.dst, f);
    if (!fs.existsSync(dst)) { missing.push(f); continue; }
    if (shaFile(set, dst) !== sha(generatedFor(set, f))) stale.push(f);
  }
  if (fs.existsSync(set.dst)) {
    for (const f of fs.readdirSync(set.dst)) {
      const p = path.join(set.dst, f);
      if (fs.statSync(p).isFile() && set.match(f) && !files.includes(f)) extra.push(f);
    }
  }
  return { stale, missing, extra };
}
/** All sets; the search-ui set's arrays at the top level (pin API) + per-set detail. */
function diff() {
  const out = { stale: [], missing: [], extra: [], sets: {} };
  for (const set of SETS) {
    const d = diffSet(set);
    out.sets[set.name] = d;
    const pfx = set.name === 'search-ui' ? '' : set.name + '/';
    out.stale.push(...d.stale.map(f => pfx + f)); out.missing.push(...d.missing.map(f => pfx + f)); out.extra.push(...d.extra.map(f => pfx + f));
  }
  return out;
}

/** Regenerate every copy (mirror). Returns the files written + removed. */
function sync() {
  const written = [], removed = [];
  for (const set of SETS) {
    fs.mkdirSync(set.dst, { recursive: true });
    const files = listSrc(set);
    for (const f of files) {
      const out = generatedFor(set, f);
      const dst = path.join(set.dst, f);
      if (!fs.existsSync(dst) || shaFile(set, dst) !== sha(out)) { fs.writeFileSync(dst, out); written.push(set.name + '/' + f); }
    }
    for (const f of fs.readdirSync(set.dst)) {
      const p = path.join(set.dst, f);
      if (fs.statSync(p).isFile() && set.match(f) && !files.includes(f)) { fs.rmSync(p); removed.push(set.name + '/' + f); }
    }
  }
  return { written, removed };
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const d = diff();
    const bad = d.stale.length + d.missing.length + d.extra.length;
    if (bad) {
      console.error(`[sync-client-search] client copy is STALE — run: node scripts/sync-client-search.js`
        + (d.stale.length ? `\n  changed: ${d.stale.join(', ')}` : '')
        + (d.missing.length ? `\n  missing: ${d.missing.join(', ')}` : '')
        + (d.extra.length ? `\n  extra (removed at source): ${d.extra.join(', ')}` : ''));
      process.exit(1);
    }
    console.log('[sync-client-search] client copy is current.');
  } else {
    const r = sync();
    console.log(`[sync-client-search] ${r.written.length} written, ${r.removed.length} removed → client/renderer/shared/`);
  }
}

module.exports = { sync, diff, diffSet, sourceFiles, generated, generatedFor, listSrc, sha, norm, SETS, BANNER_LINE, CSS_BANNER_LINE, THEME_BANNER_LINE, SRC, DST, SHARED, CLIENT_SHARED };
