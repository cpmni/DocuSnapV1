#!/usr/bin/env node
'use strict';
/**
 * scripts/sync-client-search.js — DRIFT GUARD #1 (generator half) for the shared search UI
 * (client search parity, 2026-09-13; Oracle C4).
 *
 * The search screen has ONE canonical source, src/windows/shared/search-ui/. The detached client is a
 * SEPARATE electron-builder app whose navGuard hard-restricts file:// loads to client/renderer/ and whose
 * asar packs only client/**, so it cannot load a file under src/ at runtime. It therefore ships a
 * GENERATED COPY under client/renderer/shared/search-ui/ — produced by this script, COMMITTED (so a fresh
 * clone + `electron .` works and electron-builder packs it with zero config), and regenerated by the
 * client's `prestart` / `predist` hooks. scripts/test_client_search_sync.js (in `npm run test:pins`)
 * fails whenever the committed copy is stale, so a core search edit cannot ship without its client twin.
 *
 * MIRROR semantics: files removed from the source are removed from the copy. Every copied text file gets
 * a one-line GENERATED banner (the checker hashes the copy minus that line). Line endings are copied as-is
 * (the checker normalises CRLF, so core.autocrlf cannot flip it red).
 *
 *   node scripts/sync-client-search.js          # regenerate the client copy
 *   node scripts/sync-client-search.js --check  # exit 1 if the copy is stale (no writes)
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src', 'windows', 'shared', 'search-ui');
const DST = path.join(ROOT, 'client', 'renderer', 'shared', 'search-ui');
const BANNER_LINE = '// GENERATED by scripts/sync-client-search.js from src/windows/shared/search-ui — EDIT THE SOURCE, never this copy.';
const CSS_BANNER_LINE = '/* GENERATED by scripts/sync-client-search.js from src/windows/shared/search-ui — EDIT THE SOURCE, never this copy. */';

// Files that ship to the client: the shared modules only — never the pins.
function sourceFiles() {
  return fs.readdirSync(SRC).filter(f => /\.(js|css)$/.test(f) && !/^test_/.test(f)).sort();
}
function bannerFor(f) { return f.endsWith('.css') ? CSS_BANNER_LINE : BANNER_LINE; }

// The generated content for one source file: banner + the source verbatim.
function generated(f) {
  const src = fs.readFileSync(path.join(SRC, f), 'utf8');
  const nl = src.includes('\r\n') ? '\r\n' : '\n';
  return bannerFor(f) + nl + src;
}

const norm = (s) => String(s).replace(/\r\n/g, '\n');
const sha = (s) => crypto.createHash('sha256').update(norm(s)).digest('hex');

/** Compare copy vs source. Returns { stale:[file], missing:[file], extra:[file] }. */
function diff() {
  const files = sourceFiles();
  const stale = [], missing = [], extra = [];
  for (const f of files) {
    const dst = path.join(DST, f);
    if (!fs.existsSync(dst)) { missing.push(f); continue; }
    if (sha(fs.readFileSync(dst, 'utf8')) !== sha(generated(f))) stale.push(f);
  }
  if (fs.existsSync(DST)) {
    for (const f of fs.readdirSync(DST)) if (/\.(js|css)$/.test(f) && !files.includes(f)) extra.push(f);
  }
  return { stale, missing, extra };
}

/** Regenerate the copy (mirror). Returns the list of files written + removed. */
function sync() {
  fs.mkdirSync(DST, { recursive: true });
  const files = sourceFiles();
  const written = [], removed = [];
  for (const f of files) {
    const out = generated(f);
    const dst = path.join(DST, f);
    if (!fs.existsSync(dst) || sha(fs.readFileSync(dst, 'utf8')) !== sha(out)) { fs.writeFileSync(dst, out); written.push(f); }
  }
  for (const f of fs.readdirSync(DST)) {
    if (/\.(js|css)$/.test(f) && !files.includes(f)) { fs.rmSync(path.join(DST, f)); removed.push(f); }
  }
  return { written, removed };
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const d = diff();
    const bad = d.stale.length + d.missing.length + d.extra.length;
    if (bad) {
      console.error(`[sync-client-search] client copy is STALE — run: node scripts/sync-client-search.js`
        + (d.stale.length ? `\n  changed: ${d.stale.join(', ')}` : '')
        + (d.missing.length ? `\n  missing: ${d.missing.join(', ')}` : '')
        + (d.extra.length ? `\n  extra (removed at source): ${d.extra.join(', ')}` : ''));
      process.exit(1);
    }
    console.log('[sync-client-search] client copy is current.');
  } else {
    const r = sync();
    console.log(`[sync-client-search] ${r.written.length} written, ${r.removed.length} removed → client/renderer/shared/search-ui`);
  }
}

module.exports = { sync, diff, sourceFiles, generated, sha, norm, BANNER_LINE, CSS_BANNER_LINE, SRC, DST };
