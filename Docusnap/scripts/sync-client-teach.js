#!/usr/bin/env node
'use strict';
/**
 * scripts/sync-client-teach.js — DRIFT GUARD (generator half) for the shared teach UI
 * (teach-over-client S1, 2026-09-14; the sync-client-search.js twin).
 *
 * The teach wizard has ONE canonical source, src/windows/shared/teach-ui/ (teach.js + teach.css), plus the
 * shared renderer sub-components it loads. The detached client is a SEPARATE electron-builder app whose
 * navGuard hard-restricts file:// loads to client/renderer/ and whose asar packs only client/**, so it cannot
 * load a file under src/ at runtime. It therefore ships GENERATED COPIES under client/renderer/shared/ —
 * produced by this script, COMMITTED, regenerated by the client's prestart/predist hooks. Its checker
 * (scripts/test_client_teach_sync.js, in `npm run test:pins`) fails whenever a committed copy is stale, so a
 * core teach edit cannot ship without its client twin.
 *
 * MIRROR SETS (source → destination, mirror semantics — files removed at the source are removed from the copy):
 *   teach-ui      src/windows/shared/teach-ui/*.js|css (never pins) → client/renderer/shared/teach-ui/  (+ banner)
 *   teach-shared  the shared sub-scripts the wizard loads           → client/renderer/shared/            (+ banner)
 * The theme / fonts / patterns the teach window also needs are mirrored by sync-client-search.js (shared dst);
 * the two syncs manage DISJOINT file sets in client/renderer/shared/, so neither disturbs the other.
 *
 *   node scripts/sync-client-teach.js          # regenerate every copy
 *   node scripts/sync-client-teach.js --check  # exit 1 if any copy is stale (no writes)
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const SHARED = path.join(ROOT, 'src', 'windows', 'shared');
const CLIENT_SHARED = path.join(ROOT, 'client', 'renderer', 'shared');
const SRC = path.join(SHARED, 'teach-ui');
const DST = path.join(CLIENT_SHARED, 'teach-ui');
const BANNER_LINE = '// GENERATED by scripts/sync-client-teach.js from src/windows/shared — EDIT THE SOURCE, never this copy.';
const CSS_BANNER_LINE = '/* GENERATED by scripts/sync-client-teach.js from src/windows/shared — EDIT THE SOURCE, never this copy. */';

// The shared renderer sub-components the teach wizard loads (teach/index.html). thumbs.js + dialogFocus.js
// reference the core bridge behind optional chaining (?.), so they degrade gracefully with no bridge on the
// client (no thumbnail / a direct focus); the rest are IO-free. Add a name here when the wizard loads a new one.
const SUBSCRIPTS = ['helpmode.js', 'thumbs.js', 'dialogFocus.js', 'doctype-editor.js', 'doctype-catalog.js',
                    'anchorLabel.js', 'listCaption.js', 'boxSnap.js', 'valueLocate.js', 'issuerQuality.js'];

const SETS = [
  { name: 'teach-ui',     src: SRC,    dst: DST,           match: (f) => /\.(js|css)$/.test(f) && !/^test_/.test(f), banner: (f) => (f.endsWith('.css') ? CSS_BANNER_LINE : BANNER_LINE), binary: false },
  { name: 'teach-shared', src: SHARED, dst: CLIENT_SHARED, match: (f) => SUBSCRIPTS.includes(f),                     banner: () => BANNER_LINE,                                          binary: false },
];

function listSrc(set) { return fs.existsSync(set.src) ? fs.readdirSync(set.src).filter(f => fs.statSync(path.join(set.src, f)).isFile() && set.match(f)).sort() : []; }
function sourceFiles() { return listSrc(SETS[0]); }

function generatedFor(set, f) {
  const p = path.join(set.src, f);
  const src = fs.readFileSync(p, 'utf8');
  if (!set.banner) return src;
  const nl = src.includes('\r\n') ? '\r\n' : '\n';
  return set.banner(f) + nl + src;
}
function generated(f) { return generatedFor(SETS[0], f); }

const norm = (s) => String(s).replace(/\r\n/g, '\n');
const sha = (s) => crypto.createHash('sha256').update(Buffer.isBuffer(s) ? s : norm(s)).digest('hex');
const shaFile = (set, p) => sha(fs.readFileSync(p, 'utf8'));

function diffSet(set) {
  const files = listSrc(set);
  const stale = [], missing = [], extra = [];
  for (const f of files) {
    const dst = path.join(set.dst, f);
    if (!fs.existsSync(dst)) { missing.push(f); continue; }
    if (shaFile(set, dst) !== sha(generatedFor(set, f))) stale.push(f);
  }
  if (fs.existsSync(set.dst)) {
    for (const f of fs.readdirSync(set.dst)) {
      const p = path.join(set.dst, f);
      if (fs.statSync(p).isFile() && set.match(f) && !files.includes(f)) extra.push(f);
    }
  }
  return { stale, missing, extra };
}
function diff() {
  const out = { stale: [], missing: [], extra: [], sets: {} };
  for (const set of SETS) {
    const d = diffSet(set);
    out.sets[set.name] = d;
    const pfx = set.name === 'teach-ui' ? '' : set.name + '/';
    out.stale.push(...d.stale.map(f => pfx + f)); out.missing.push(...d.missing.map(f => pfx + f)); out.extra.push(...d.extra.map(f => pfx + f));
  }
  return out;
}
function sync() {
  const written = [], removed = [];
  for (const set of SETS) {
    fs.mkdirSync(set.dst, { recursive: true });
    const files = listSrc(set);
    for (const f of files) {
      const out = generatedFor(set, f);
      const dst = path.join(set.dst, f);
      if (!fs.existsSync(dst) || shaFile(set, dst) !== sha(out)) { fs.writeFileSync(dst, out); written.push(set.name + '/' + f); }
    }
    for (const f of fs.readdirSync(set.dst)) {
      const p = path.join(set.dst, f);
      if (fs.statSync(p).isFile() && set.match(f) && !files.includes(f)) { fs.rmSync(p); removed.push(set.name + '/' + f); }
    }
  }
  return { written, removed };
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const d = diff();
    const bad = d.stale.length + d.missing.length + d.extra.length;
    if (bad) {
      console.error(`[sync-client-teach] client copy is STALE — run: node scripts/sync-client-teach.js`
        + (d.stale.length ? `\n  changed: ${d.stale.join(', ')}` : '')
        + (d.missing.length ? `\n  missing: ${d.missing.join(', ')}` : '')
        + (d.extra.length ? `\n  extra (removed at source): ${d.extra.join(', ')}` : ''));
      process.exit(1);
    }
    console.log('[sync-client-teach] client copy is current.');
  } else {
    const r = sync();
    console.log(`[sync-client-teach] ${r.written.length} written, ${r.removed.length} removed → client/renderer/shared/`);
  }
}

module.exports = { sync, diff, diffSet, sourceFiles, generated, generatedFor, listSrc, sha, norm, SETS, BANNER_LINE, CSS_BANNER_LINE, SUBSCRIPTS, SRC, DST, SHARED, CLIENT_SHARED };
